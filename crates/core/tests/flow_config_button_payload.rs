#[test]
fn button_payload_nodeid_slot_existing_payload_with_ca_round_trips_byte_identically() {
    let props = ButtonPayload {
        flow_version_id: some("222"),
        button_id: some("333"),
        comment_automation_id: some("444"),
        ..payload("111")
    };
    let encoded = fc::encode_button_payload(&props);
    assert_eq!(encoded, "111:222:333::::444");
    assert_eq!(fc::decode_button_payload(&encoded, false), Some(props));
}

#[test]
fn button_payload_nodeid_slot_flowid_nodeid_round_trips() {
    let props = ButtonPayload {
        node_id: some("555"),
        ..payload("111")
    };
    let encoded = fc::encode_button_payload(&props);
    assert_eq!(encoded, "111:::::::555");
    assert_eq!(fc::decode_button_payload(&encoded, false), Some(props));
}

#[test]
fn button_payload_nodeid_slot_flowid_alone_stays_bare_and_rejects_a_non_numeric_nodeid() {
    assert_eq!(fc::encode_button_payload(&payload("111")), "111:");
    assert_eq!(fc::decode_button_payload("111:::::::abc", false), None);
}
