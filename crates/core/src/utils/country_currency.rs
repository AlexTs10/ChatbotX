/// `primaryCurrencyForCountry`: `None` for an empty or unknown code, or a
/// country without a currency.
pub fn primary_currency_for_country(country_code: Option<&str>) -> Option<&'static str> {
    let code = crate::js::trim(country_code?).to_uppercase();
    if code.is_empty() {
        return None;
    }
    COUNTRY_CURRENCIES
        .iter()
        .find(|(c, _)| *c == code)
        .and_then(|(_, currency)| *currency)
}
