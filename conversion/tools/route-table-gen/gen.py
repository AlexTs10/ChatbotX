"""Generate crates/api/src/routes/table.rs (the public oRPC route table).

Input 1: public-ops.json, the operations of the original `/api/spec.json`
(operationId, method, path, x-mcp.scope), taken from the original parity stack.
Input 2: the builder source (apps/builder/src), scanned for `.route({ method, path })`
to name the source module of each operation (used by the scope-wiring tests).

Run from the repo root: python3 conversion/tools/route-table-gen/gen.py
"""
import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../../.."))
SRC = os.path.join(ROOT, "apps/builder/src")
OUT = os.path.join(ROOT, "crates/api/src/routes/table.rs")

ops = json.load(open(os.path.join(HERE, "public-ops.json")))
by_key = {(o["method"], o["path"]): o for o in ops}
route_re = re.compile(r"\.route\(\s*\{(.*?)\}\s*\)", re.S)
module_of = {}
for d, _, files in os.walk(SRC):
    if "node_modules" in d or "__tests__" in d:
        continue
    for f in sorted(files):
        if not f.endswith(".ts"):
            continue
        path = os.path.join(d, f)
        src = open(path).read()
        if ".route(" not in src:
            continue
        consts = dict(re.findall(r'const\s+([A-Za-z_0-9]+)\s*=\s*"([^"]*)"', src))
        rel = os.path.relpath(path, SRC)[: -len(".ts")]
        if rel.endswith("/index"):
            rel = rel[: -len("/index")]
        for body in route_re.findall(src):
            m = re.search(r'method:\s*"(\w+)"', body)
            pm = re.search(r'path:\s*("([^"]*)"|`([^`]*)`|([A-Za-z_][A-Za-z_0-9]*))', body)
            if not pm:
                continue
            if pm.group(2) is not None:
                p = pm.group(2)
            elif pm.group(3) is not None:
                p = re.sub(r"\$\{([A-Za-z_0-9]+)\}", lambda x: consts.get(x.group(1), "??"), pm.group(3))
            else:
                p = consts.get(pm.group(4), "??")
            o = by_key.get((m.group(1) if m else "POST", p))
            if o and o["id"] not in module_of:
                module_of[o["id"]] = rel

# Operations built by shared route factories: the module of their namespace.
group_modules = collections.defaultdict(collections.Counter)
for o in ops:
    if o["id"] in module_of:
        group_modules[o["id"].rsplit(".", 1)[0]][module_of[o["id"]]] += 1
FACTORY = "features/channel-integrations/api/public"
for o in ops:
    if o["id"] not in module_of:
        counter = group_modules.get(o["id"].rsplit(".", 1)[0])
        module_of[o["id"]] = counter.most_common(1)[0][0] if counter else FACTORY

MOBILE_PASSWORD_CHANGE = {"me.get", "me.changePassword"}


def auth(o):
    if o["id"].startswith("channels.") and o["path"].startswith("/v1/channels/api/"):
        return "RouteAuth::ChannelToken"
    if o["id"].startswith("me."):
        return "RouteAuth::MobileUserPasswordChange" if o["id"] in MOBILE_PASSWORD_CHANGE else "RouteAuth::MobileUser"
    scope = o["scope"]
    scopes = scope if isinstance(scope, list) else [scope]
    assert all(scopes), o
    return "RouteAuth::WorkspaceToken(&[" + ", ".join(f'"{s}"' for s in scopes) + "])"


lines = [
    "//! GENERATED by `conversion/tools/route-table-gen/gen.py`; do not edit by hand.",
    "//!",
    "//! Every operation of the original public oRPC router (`publicRouter`, served",
    "//! under `/api`): operation id, method, oRPC path, auth, source module.",
    "",
    "use super::{PublicRoute, RouteAuth};",
    "",
    "/// The public routes, in the order of the original OpenAPI document.",
    "#[rustfmt::skip]",
    "pub static PUBLIC_ROUTES: &[PublicRoute] = &[",
]
for o in ops:
    lines.append(
        f'    PublicRoute {{ id: "{o["id"]}", method: "{o["method"]}", path: "{o["path"]}", auth: {auth(o)}, module: "{module_of[o["id"]]}" }},'
    )
lines.append("];")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"{len(ops)} routes -> {os.path.relpath(OUT, ROOT)}")
